import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { uuid } from "./fixtures/planner-headless.mjs";

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLANNER_PLAYWRIGHT_MODULE ?? "playwright-core");
const origin = "http://127.0.0.1:" + (process.env.COMPOSER_C8_TEST_PORT ?? "3224");
const query = "?scenario=M11M12&durable=1&delayRead=1200";
const browser = await chromium.launch({ channel: "chrome", headless: true });

try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: "reduce" });
  await context.route("**/*", route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const root = page.locator("[data-composer]");
  const library = page.locator("[data-library]");
  const finance = page.locator("[data-month-read]");
  const editor = page.locator("[data-project-editor]");
  const cinema = page.locator("[data-cinema-editor]");
  const linked = id => editor.locator(`[data-linked-intention="${id}"] > button`);
  const button = (scope, name) => scope.getByRole("button", { name, exact: typeof name === "string" });
  const parentId = uuid(11120), childId = uuid(11121);
  const read = async () => (await page.request.get(origin + "/draft" + query)).json();
  const digest = () => root.getAttribute("data-digest");
  const save = async previous => {
    await page.waitForFunction(old => {
      const root = document.querySelector("[data-composer]");
      return root?.dataset.saveState === "SAVED" && root.dataset.digest !== old;
    }, previous);
    const { active } = await read();
    assert.equal(active.digest, await digest());
    return active;
  };
  const group = async key => {
    const section = finance.locator(`[data-month-group="${key}"]`);
    if (await section.getAttribute("open") === null) await section.locator(":scope > summary").click();
    return section;
  };
  const occurrence = (draft, id) => draft.semanticState.contexts.find(item => item.contextOccurrenceId === id);
  const progress = (scope, id) => scope.locator(`[data-intention-progress="${id}"]`);

  await page.goto(origin + "/" + query);
  await root.locator('[data-hud-status]').waitFor();
  assert.match(await root.locator('[data-hud-status]').innerText(), /Projection bloquée/u);
  const initialDigest = await digest();
  assert.equal((await read()).active, null);
  await root.locator("[data-open-finances]").click();
  await finance.waitFor();
  const charges = await group("charges");
  await charges.locator("[data-month-row] > summary").first().click();
  assert.match(await charges.innerText(), /Charge prévue · paiement non attesté/u);
  const chargeLink = charges.getByRole("link", { name: /Ajuster la prévision/ }).first();
  assert.match(await chargeLink.getAttribute("href"), /month=2026-11.*focus=update%3Aitem%3Aobligation%3Arent/u);
  assert.match(await finance.locator("[data-month-missing]").innerText(), /Swile.*chargement|chargement.*Swile/su);
  assert.match(await finance.locator("[data-month-missing]").innerText(), /Edenred/u);
  const savings = await group("savings");
  assert.equal(await savings.locator('[data-protected="true"] [data-month-control-target]').count(), 0);
  const courses = await group("groceries");
  const target = courses.locator("[data-courses-target]");
  await target.locator("xpath=ancestor::details[1]/summary").click();
  assert.match(await target.innerText(), /Réel constaté : 42,00/u);
  const controlId = await target.getAttribute("data-courses-target");
  await button(target, "Ajuster la cible").click();
  await target.getByRole("textbox", { name: "Nouvelle cible Courses (€)" }).fill("350");
  await button(target, "Conserver la cible dans le brouillon").click();
  const monthly = await save(initialDigest);
  assert.equal(monthly.semanticState.controls.find(item => item.decisionSlotKey === controlId).value.amount, "350.00");
  assert.equal(await target.evaluate(node => node.contains(document.activeElement)), true);
  await button(courses, "Voir la carte sur le Board").click();
  await finance.waitFor({ state: "hidden" });
  await root.locator(`[data-control="${controlId}"][data-focused="true"]`).waitFor();

  const search = library.getByRole("textbox", { name: "Rechercher une intention" });
  await button(library, "Mes intentions").click();
  await search.fill("Sortie de recette");
  await library.locator(`[data-library-existing-action="${parentId}"]`).click();
  assert.match(await progress(editor, parentId).innerText(), /novembre 2026 · Sauvegardé · Projection bloquée/u);
  await button(editor, "Modifier la date du projet").click();
  const date = editor.getByLabel("Date du projet", { exact: true });
  await date.fill("2026-12-02");
  await button(editor, "Conserver la date du projet").click();
  assert.match(await editor.getByRole("alert").innerText(), /date valide dans le mois/u);
  assert.equal((await read()).active.version, monthly.version);
  await date.fill("2026-11-21");
  await button(editor, "Conserver la date du projet").click();
  const rescheduled = await save(monthly.digest);
  assert.equal(occurrence(rescheduled, parentId).fields.plannedDate, "2026-11-21");
  assert.deepEqual(occurrence(rescheduled, childId), occurrence(monthly, childId));
  await linked(childId).click();
  await button(cinema, /^Séance/u).click();
  await cinema.getByLabel("Heure de la séance").fill("17:45");
  await button(cinema, "Conserver le jour et l’heure").click();
  const final = await save(rescheduled.digest);
  assert.equal(occurrence(final, childId).fields.plannedTime, "17:45");
  assert.equal(occurrence(final, childId).parentContextOccurrenceId, parentId);
  assert.deepEqual(occurrence(final, childId).slotSelections, occurrence(monthly, childId).slotSelections);
  assert.deepEqual(occurrence(final, parentId).slotSelections, occurrence(monthly, parentId).slotSelections);
  assert.deepEqual(final.semanticState.controls, monthly.semanticState.controls);
  assert.deepEqual(final.semanticState.contexts.map(item => item.contextOccurrenceId), [parentId, childId]);
  assert.equal(final.draftId, monthly.draftId);
  assert.equal(final.version, monthly.version + 2);
  const savedVersion = final.version;
  await button(cinema, "Voir les informations du mois à compléter").click();
  await finance.waitFor();
  await page.locator("[data-financial-inspector]").getByRole("button", { name: /^Revenir à /u }).click();
  await cinema.waitFor();
  assert.equal((await read()).active.version, savedVersion);
  assert.match(await progress(cinema, childId).innerText(), /Sauvegardé · Projection bloquée/u);
  await button(cinema, /Revenir au projet/u).click();
  await linked(childId).waitFor();

  await page.reload();
  await button(root, "Ouvrir le projet").click();
  assert.match(await progress(editor, parentId).innerText(), /Sauvegardé · Projection bloquée/u);
  assert.match(await editor.innerText(), /21 nov/u);
  const snapshot = await read();
  assert.deepEqual(snapshot.active, final);
  assert.equal(snapshot.archives.length, 0);
  assert.equal(snapshot.activePlanRevisionNumber, 0);
  assert.equal(await digest(), final.digest);
  if (process.env.COMPOSER_CONTINUITY_SCREENSHOT) await page.screenshot({ path: process.env.COMPOSER_CONTINUITY_SCREENSHOT });
  await button(editor, "Retour au mois").click();
  await button(library, "À ajouter").click();
  await search.fill("Mascara");
  await search.press("Enter");
  assert.equal(await library.locator('[data-library-add-action]:focus').count(), 1);
  assert.equal((await read()).active.version, final.version);
  const evidence = await (await page.request.get(origin + "/evidence" + query)).json();
  assert.equal(evidence.remoteWrites, 0);
  assert.equal(evidence.historicalCanaryWrites, 0);
  assert.equal(evidence.log.some(event => event.kind === "APPLY"), false);
  assert.deepEqual(errors, []);
  console.log("M11/M12 · budget et réglage mensuel, dates, reprise exacte du projet et de son enfant, projection bloquée et aucune création par recherche : PASS");
} finally {
  await browser.close();
}
